// Round to the nearest 10 for clean pricing.
const r10 = (n: number) => Math.round(n / 10) * 10;

// MRP carries a ~20% markup over the selling price.
const withMrp = (price: number) => ({ price, mrp: r10(price * 1.2) });

function pickleVariants(pricePerKg: number) {
  return [
    {
      id: "v-250",
      label: "250 g",
      grams: 250,
      ...withMrp(r10(pricePerKg / 4)),
    },
    {
      id: "v-500",
      label: "500 g",
      grams: 500,
      ...withMrp(r10(pricePerKg / 2)),
    },
    { id: "v-1000", label: "1 kg", grams: 1000, ...withMrp(pricePerKg) },
  ];
}

function powderVariants(pricePerKg: number) {
  return [
    {
      id: "v-200",
      label: "200 g",
      grams: 200,
      ...withMrp(r10(pricePerKg / 5)),
    },
    {
      id: "v-500",
      label: "500 g",
      grams: 500,
      ...withMrp(r10(pricePerKg / 2)),
    },
    { id: "v-1000", label: "1 kg", grams: 1000, ...withMrp(pricePerKg) },
  ];
}

function snackVariants(pricePerKg: number) {
  return [
    {
      id: "v-200",
      label: "200 g",
      grams: 200,
      ...withMrp(r10(pricePerKg / 5)),
    },
    {
      id: "v-400",
      label: "400 g",
      grams: 400,
      ...withMrp(r10((pricePerKg * 2) / 5)),
    },
    { id: "v-1000", label: "1 kg", grams: 1000, ...withMrp(pricePerKg) },
  ];
}

